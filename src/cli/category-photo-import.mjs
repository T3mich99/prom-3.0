import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { inspectPngBytes } from '../photos/real-photo-production.mjs';
import { validatePhotoProductionPlan } from '../photos/photo-production-plan.mjs';
import { assertCurrentPhotoStyle } from '../photos/photo-style-profile.mjs';
import { validatePhotoArtifacts } from '../photos/photo-quality.mjs';

function normalizedVisibleText(value) {
  return String(value ?? '').normalize('NFKC').replace(/\s+/gu, ' ').trim().toLocaleLowerCase('uk-UA');
}

function auditedVisualQa(plan, visualQa) {
  if (visualQa === undefined) return undefined;
  if (!visualQa || !Array.isArray(visualQa.photos)) throw new TypeError('Codex visual QA with observedText is required');
  const audited = structuredClone(visualQa);
  for (const planned of plan.photos) {
    const reviewed = audited.photos.find((item) => item?.photoIndex === planned.index);
    if (!reviewed || !Array.isArray(reviewed.observedText) || reviewed.observedText.some((value) => typeof value !== 'string')) {
      throw new TypeError(`Photo ${planned.index} visual QA requires observedText from the rendered image`);
    }
    const expected = (planned.text ?? []).map((item) => normalizedVisibleText(item.value)).filter(Boolean);
    const observed = reviewed.observedText.map(normalizedVisibleText).filter(Boolean);
    const matches = JSON.stringify(expected) === JSON.stringify(observed);
    reviewed.checks = { ...reviewed.checks };
    if (!matches) {
      reviewed.checks.textReadable = false;
      if (observed.some((value) => !expected.includes(value))) reviewed.checks.noFabricatedClaims = false;
      reviewed.status = 'REWORK';
      audited.status = 'REWORK';
    }
  }
  return audited;
}

/** Import images already generated by Codex. Never calls a provider, API or host. */
export async function importCodexPhotoFiles({ plan, sourceFacts, files, visualQa }) {
  validatePhotoProductionPlan(plan);
  if (plan.status !== 'READY' || !Array.isArray(files) || files.length !== 5) throw new TypeError('Import requires a READY plan and exactly five files');
  if (new Set(files.map((file) => file.photoIndex)).size !== 5) throw new TypeError('File photoIndex values must be unique');
  const artifacts = [];
  for (const photo of plan.photos) {
    assertCurrentPhotoStyle(photo.visualDirection.styleProfile);
    const file = files.find((item) => item.photoIndex === photo.index);
    if (!file || typeof file.path !== 'string' || !path.isAbsolute(file.path) || typeof file.sha256 !== 'string') throw new TypeError('Every reviewed file requires its photoIndex, absolute path and sha256');
    const inspected = inspectPngBytes(await fs.readFile(file.path));
    if (file.sha256 !== inspected.hash) throw new Error(`Photo ${photo.index} changed after review`);
    artifacts.push({ productKey: plan.productKey, photoIndex: photo.index, role: photo.role,
      asset: { path: file.path, width: inspected.width, height: inspected.height, format: 'png' }, hash: inspected.hash,
      claimsUsed: structuredClone(photo.verifiedClaims), text: structuredClone(photo.text), sourceImageRefs: structuredClone(photo.sourceImageRefs),
      message: photo.visualDirection.creativeConcept?.message ?? photo.objective,
      composition: photo.visualDirection.compositionIntent, productPosition: photo.visualDirection.positionKey,
    });
  }
  const verifiedVisualQa = auditedVisualQa(plan, visualQa);
  const quality = validatePhotoArtifacts({ plan, artifacts, sourceFacts,
    ...(verifiedVisualQa === undefined ? {} : { visualQa: verifiedVisualQa }) }, { requireVisualQa: true });
  return { productKey: plan.productKey, version: plan.version, plan: structuredClone(plan), artifacts,
    ...(verifiedVisualQa === undefined ? {} : { visualQa: verifiedVisualQa }), quality };
}

export async function runPhotoImportCli(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    if (!['--input', '--output'].includes(argv[i]) || !argv[i + 1] || args[argv[i]]) throw new Error('Usage: npm run category:photos -- --input import.json --output photo-artifact.json');
    args[argv[i]] = argv[i + 1];
  }
  if (!args['--input'] || !args['--output']) throw new Error('Both --input and --output are required');
  const inputPath = path.resolve(args['--input']);
  const outputPath = path.resolve(args['--output']);
  const input = JSON.parse(await fs.readFile(inputPath, 'utf8'));
  if (outputPath === inputPath || input.files?.some((file) => path.resolve(file.path) === outputPath)) throw new Error('Output must not overwrite input or images');
  const result = await importCodexPhotoFiles(input);
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, JSON.stringify(result, null, 2) + '\n', { flag: 'wx' });
  return result;
}

