const shorten = (s, max) => {
  const t = clean(s);
  if (t.length <= max) return t;
  const cut = t.slice(0, max - 1).replace(/\s+\S*$/, '').trim();
  return `${cut}…`;
};

const makeKeywords = (lang, title, category, purpose, facts) => {
  const ru = lang === 'ru';
  const base = shorten(title, 28);
  const cat = shorten(category, 22).toLowerCase();
  const purposeShort = shorten((ru ? purpose.ru : purpose.ua).replace(/^.*?для /i, '').replace(/[.,].*$/, ''), 18);
  const tail = ru ? [
    base, `купить ${base}`, `заказать ${base}`, `${base} цена`, `${base} доставка`, `${base} онлайн`,
    `${base} для дома`, `${base} для квартиры`, `${base} для быта`, `${base} для повседневного использования`,
    cat, `купить ${cat}`, `заказать ${cat}`, `${cat} цена`, `${cat} для дома`, `${cat} для быта`,
    `практичный ${cat}`, `удобный ${cat}`, `товар для ${cat}`, `аксессуар для ${cat}`,
    `решение для ${purposeShort}`, `товар для ${purposeShort}`, `для ${purposeShort}`, `категория ${cat}`, `выбор ${cat}`,
  ] : [
    base, `купити ${base}`, `замовити ${base}`, `${base} ціна`, `${base} доставка`, `${base} онлайн`,
    `${base} для дому`, `${base} для квартири`, `${base} для побуту`, `${base} для щоденного використання`,
    cat, `купити ${cat}`, `замовити ${cat}`, `${cat} ціна`, `${cat} для дому`, `${cat} для побуту`,
    `практичний ${cat}`, `зручний ${cat}`, `товар для ${cat}`, `аксесуар для ${cat}`,
    `рішення для ${purposeShort}`, `товар для ${purposeShort}`, `для ${purposeShort}`, `категорія ${cat}`, `вибір ${cat}`,
  ];
  const factPhrase = facts.filter((x) => /колір|цвет|матеріал|материал|розмір|размер|об'єм|объем|кількість|количество/i.test(x)).slice(0, 3);
  const values = [...tail, ...factPhrase];
  const result = [];
  for (const phrase of values) {
    const item = clean(phrase).replace(/\b(?:UG\s*OPT|supplier|поставщик|артикул|SKU|source)\b/gi, '').trim();
    if (!item || /\b(?:AND|AE|XL|MAG|NJ|RD|QC|LY|YLN|XWL|YACM|RT)\s*[- ]?\s*\d+/i.test(item)) continue;
    if (result.includes(item)) continue;
    const next = [...result, item].join(', ');
    if (next.length > 1024) break;
    result.push(item);
  }
  const fallback = ru ? [
    `${cat} для дома`, `${cat} для квартиры`, `${cat} для быта`, `${cat} на каждый день`, `${cat} для семьи`,
    `${cat} по назначению`, `${cat} с характеристиками`, `${cat} с доставкой`, `${cat} в Украине`, `${cat} онлайн`,
    `покупка ${cat}`, `выбор ${cat}`, `каталог ${cat}`, `товары ${cat}`, `решение для дома`,
  ] : [
    `${cat} для дому`, `${cat} для квартири`, `${cat} для побуту`, `${cat} на щодень`, `${cat} для сім’ї`,
    `${cat} за призначенням`, `${cat} з характеристиками`, `${cat} з доставкою`, `${cat} в Україні`, `${cat} онлайн`,
    `купівля ${cat}`, `вибір ${cat}`, `каталог ${cat}`, `товари ${cat}`, `рішення для дому`,
  ];
  for (const phrase of fallback) {
    const item = clean(phrase);
    const next = [...result, item].join(', ');
    if (result.length >= 25 || next.length > 1024 || result.includes(item)) continue;
    result.push(item);
  }
  if (result.length < 25) {
    const generic = ru ? ['практичный товар для дома', 'товар для ежедневных задач', 'удобный товар для быта'] : ['практичний товар для дому', 'товар для щоденних завдань', 'зручний товар для побуту'];
    for (const item of generic) if (!result.includes(item) && result.length < 25) result.push(item);
  }
  return dedupe(result).slice(0, 25).join(', ');
};

