const translateUa = (text) => {
  let out = String(text ?? '');
  for (const [from, to] of phraseRu) out = out.replace(new RegExp(from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), to);
  return out.replace(/пластиковаяя/gi, 'пластиковая')
    .replace(/посудв/gi, 'посуду')
    .replace(/с стерилизацией/gi, 'со стерилизацией')
    .replace(/\s{2,}/g, ' ').replace(/\s+([,.])/g, '$1').trim();
};

const sentenceCaseRu = (text) => {
  const s = String(text ?? '').replace(/\s{2,}/g, ' ').trim();
  const lower = s.replace(/[А-ЯЁа-яё]+/g, (word, offset) => offset === 0 ? word : word.toLowerCase());
  return lower.replace(/^([а-яё])/i, (m) => m.toUpperCase());
};

const normalizeUa = (text) => String(text ?? '')
  .replace(/\b(?:AND|AE|XL|MAG|NJ|RD|QC|LY|YLN|XWL|YACM|RT|m-|K)\s*[- ]?\s*[A-Z0-9-]+\b/gi, '')
  .replace(/\b(?:Raincoat|Ivy Grip Tape|Water Saver|Fur Wizard|Magic Brush|VACCUM BAG|Shower set|DANCE MAT|NON CONTACT|Anti Lost|Smart Tuya)\b/gi, '')
  .replace(/\s{2,}/g, ' ').replace(/\s+([,.])/g, '$1').trim();

