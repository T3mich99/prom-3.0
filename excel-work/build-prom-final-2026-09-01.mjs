const toBuyForm = (text, lang) => {
  const words = clean(text).split(/\s+/);
  if (!words.length) return clean(text);
  const prep = words.findIndex((word) => /^(для|до|на)$/i.test(word));
  const index = prep > 0 ? prep - 1 : words.length - 1;
  const word = words[index];
  const feminine = /[ая]$/i.test(word);
  const feminineAccusative = (value) => value
    .replace(/аяся$/i, 'уюся')
    .replace(/ая$/i, 'ую')
    .replace(/яя$/i, 'юю')
    .replace(/я$/i, 'ю')
    .replace(/а$/i, 'у');
  if (lang === 'ru') {
    if (feminine) words[index] = feminineAccusative(word);
  } else if (feminine) {
    words[index] = feminineAccusative(word);
  }
  if (feminine) {
    for (let i = index - 1, changed = 0; i >= 0 && changed < 2; i--, changed++) {
      const adjective = words[i];
      if (/^(для|до|на|с|со|из|и|или|та|й|з|із|зі)$/i.test(adjective)) break;
      if (/[ая]ся$/i.test(adjective) || /[ая]$/i.test(adjective)) words[i] = feminineAccusative(adjective);
      else if (/(ый|ий|ой)$/i.test(adjective)) words[i] = adjective.replace(/(ый|ий|ой)$/i, 'ую');
      else break;
    }
  }
  return words.join(' ');
};

