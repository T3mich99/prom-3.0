const buildPhotoLinks = (code, p) => {
  const links = [];
  let currentAi = 0;
  let fallback = 0;
  const notes = [];
  for (let i = 0; i < roles.length; i++) {
    const name = `${code}_${roles[i]}.png`;
    const current = drive[name];
    if (current?.id && !current.fallback) {
      links.push(publicDriveUrl(current));
      currentAi++;
      continue;
    }
    if (current?.id && current.fallback) {
      links.push(publicDriveUrl(current));
      fallback++;
      notes.push(`${roles[i]}: резерв Drive`);
      continue;
    }
    const old = oldDrive[name];
    if (old?.id) {
      links.push(publicDriveUrl(old));
      fallback++;
      notes.push(`${roles[i]}: резервное фото Drive`);
      continue;
    }
    const original = sourceImage(p, i);
    if (original) {
      links.push(original);
      fallback++;
      notes.push(`${roles[i]}: исходная ссылка поставщика`);
    }
  }
  if (links.length < 5) {
    const last = links.at(-1) || '';
    while (links.length < 5 && last) links.push(last);
    if (links.length < 5) notes.push('Не удалось найти 5 ссылок');
  }
  return { links, currentAi, fallback, notes };
};

const orderedReplace = (text, pairs) => {
  let out = String(text ?? '');
  for (const [from, to] of pairs.sort((a, b) => b[0].length - a[0].length)) {
    const escaped = from.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&');
    out = out.replace(new RegExp(`(?<!\\p{L})${escaped}(?!\\p{L})`, 'giu'), to);
  }
  return out.replace(/\s{2,}/g, ' ').replace(/\s+([,.])/g, '$1').trim();
};

